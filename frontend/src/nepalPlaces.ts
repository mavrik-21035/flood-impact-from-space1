export function searchNepalPlaces(prefixOrQuery: string, limit = 8): PlaceItem[] {
  const query = prefixOrQuery.trim().toLowerCase();
  if (!query) return [];

  const startsWithMatches: PlaceItem[] = [];
  const containsMatches: PlaceItem[] = [];

  for (const place of NEPAL_PLACES) {
    const nameLower = place.name.toLowerCase();
    const displayLower = place.display.toLowerCase();
    const aliasesLower = place.aliases.map((a) => a.toLowerCase());

    const isExactOrStartsWith =
      nameLower.startsWith(query) ||
      aliasesLower.some((a) => a.startsWith(query));

    if (isExactOrStartsWith) {
      startsWithMatches.push(place);
    } else if (
      nameLower.includes(query) ||
      displayLower.includes(query) ||
      aliasesLower.some((a) => a.includes(query))
    ) {
      containsMatches.push(place);
    }
  }

  return [...startsWithMatches, ...containsMatches].slice(0, limit);
}
